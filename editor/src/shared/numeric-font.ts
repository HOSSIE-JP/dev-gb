// Original MIT-licensed 8x8 numeric font. Eight rows, with the last column
// reserved as a gutter so adjacent score digits remain distinct at 1x scale.
const rows = [
    [0x7c,0xc6,0xc6,0xc6,0xc6,0xc6,0xc6,0x7c],
    [0x18,0x38,0x78,0x18,0x18,0x18,0x18,0x7e],
    [0x7c,0xc6,0x06,0x0c,0x18,0x30,0x60,0xfe],
    [0x7c,0xc6,0x06,0x3c,0x06,0x06,0xc6,0x7c],
    [0x0c,0x1c,0x3c,0x6c,0xcc,0xfe,0x0c,0x0c],
    [0xfe,0xc0,0xc0,0xfc,0x06,0x06,0xc6,0x7c],
    [0x3c,0x60,0xc0,0xfc,0xc6,0xc6,0xc6,0x7c],
    [0xfe,0xc6,0x06,0x0c,0x18,0x30,0x30,0x30],
    [0x7c,0xc6,0xc6,0x7c,0xc6,0xc6,0xc6,0x7c],
    [0x7c,0xc6,0xc6,0xc6,0x7e,0x06,0x0c,0x78],
];
export const numericGlyphs: Record<string, number[]> = Object.fromEntries(
    rows.map((glyph, digit) => [String(digit), glyph.flatMap(row =>
        Array.from({length:8}, (_, x) => row & (0x80 >> x) ? 3 : 0))]),
);
